function getLang() { return localStorage.getItem('lang') || 'en'; }
function setLang(lang) { localStorage.setItem('lang', lang); applyLang(lang); }

function t(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || (translations['en'][key]) || key;
}

// Cycles: ar → ku → en → ar
const LANG_CYCLE = { ar: 'ku', ku: 'en', en: 'ar' };
// Button label shows the NEXT language in the cycle
const LANG_LABELS = { ar: 'کو', ku: 'EN', en: 'ع' };

function applyLang(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ar' || lang === 'ku') ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  const btn = document.getElementById('langToggleBtn');
  if (btn) btn.textContent = LANG_LABELS[lang] || 'EN';
}

function toggleLang() {
  setLang(LANG_CYCLE[getLang()] || 'ar');
  window.location.reload();
}

document.addEventListener('DOMContentLoaded', () => applyLang(getLang()));
